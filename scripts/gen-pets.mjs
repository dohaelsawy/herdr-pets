// Regenerates mods/pets/pets.js from a checkout of vscode-pets' source.
//   node scripts/gen-pets.mjs <path to vscode-pets/src> <tag>
// Reads TypeScript as text; it never executes upstream code.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [src, tag] = process.argv.slice(2);
if (!src || !tag) {
  console.error("usage: node scripts/gen-pets.mjs <vscode-pets/src> <tag>");
  process.exit(1);
}
const read = (p) => readFileSync(join(src, p), "utf8");

// `export const enum Name { key = 'value', ... }` -> { key: value }
function parseEnum(text, name) {
  const body = text.match(new RegExp(`enum ${name} \\{([\\s\\S]*?)\\n\\}`))?.[1];
  if (!body) throw new Error(`enum ${name} not found`);
  const out = {};
  for (const m of body.matchAll(/(\w+)\s*=\s*(?:'([^']*)'|(\d+))/g)) out[m[1]] = m[2] ?? Number(m[3]);
  return out;
}

const types = read("common/types.ts");
const COLOR = parseEnum(types, "PetColor");
const TYPE = parseEnum(types, "PetType");
const SPEED = parseEnum(types, "PetSpeed");
const STATE = parseEnum(read("panel/states.ts"), "States");

// v1 has no ball and no friends: these states are removed everywhere.
const DROPPED = new Set(["chase", "idle-with-ball", "chase-friend"]);

// What upstream does in code rather than data. Checked against 1.37.0.
const OVERRIDES = {
  finley: { bubble: "Hi! 👋" },
  horse: { bubble: "Neigh!" },
  skeleton: { bubble: "☠️", bubbleByColor: { orange: "🎃", warrior: "🏴‍☠️" } },
  squirrel: {
    bubbles: ["🌰?", "🍕?", "🥨?", "🥜?", "🥡?", "🍏?"],
    speedFactor: 1.15,
    climbSpeed: 5.5, // 7 px/tick with a variation averaging -1.5
    fallSpeed: 15,
    climbRange: [0.3, 0.8], // share of the panel height
  },
};

// class name -> speed, from createPet's switch
const speedOf = {};
for (const m of read("panel/pets.ts").matchAll(/return new (\w+)\(\.\.\.standardPetArguments, PetSpeed\.(\w+)\)/g)) {
  speedOf[m[1]] = SPEED[m[2]];
}

// The string literals in a piece of TypeScript, in order. It skips // comments, so an
// apostrophe in a comment (// Conker's Bad Fur Day) is not taken for a quote.
function strings(body) {
  const out = [];
  for (let i = 0; i < body.length; i++) {
    const c = body[i];
    if (c === "/" && body[i + 1] === "/") {
      while (i < body.length && body[i] !== "\n") i++;
    } else if (c === "'" || c === '"') {
      let text = "";
      for (i++; i < body.length && body[i] !== c; i++) text += body[i] === "\\" ? body[++i] : body[i];
      out.push(text);
    }
  }
  return out;
}

const pets = {};
for (const file of readdirSync(join(src, "panel/pets")).filter((f) => f.endsWith(".ts")).sort()) {
  const text = read(`panel/pets/${file}`);
  const cls = text.match(/export class (\w+) extends BasePetType/)?.[1];
  const label = text.match(/\n\s+label = '([^']+)'/)?.[1];
  if (!cls || !label) throw new Error(`${file}: no class or label`);
  if (!Object.values(TYPE).includes(label)) throw new Error(`${file}: ${label} is not a PetType`);
  if (!(cls in speedOf)) throw new Error(`${file}: no speed for ${cls}`);

  const colors = [...text.match(/static possibleColors = \[([\s\S]*?)\]/)[1].matchAll(/PetColor\.(\w+)/g)].map((m) => COLOR[m[1]]);
  const start = STATE[text.match(/startingState: States\.(\w+)/)[1]];
  const sequence = {};
  for (const m of text.matchAll(/state: States\.(\w+),[\s\S]*?possibleNextStates: \[([\s\S]*?)\]/g)) {
    const state = STATE[m[1]];
    if (DROPPED.has(state)) continue;
    // Upstream repeats a next state to weight it; the repeats are kept.
    sequence[state] = [...m[2].matchAll(/States\.(\w+)/g)].map((n) => STATE[n[1]]).filter((s) => !DROPPED.has(s));
  }
  const emojiBody = text.match(/get emoji\(\): string \{([\s\S]*?)\n    \}/)?.[1] ?? "";
  const emoji = strings(emojiBody).at(-1);
  const names = strings(text.match(/_NAMES: ReadonlyArray<string> = \[([\s\S]*?)\];/)[1]);
  if (!colors.length || !emoji || !names.length || !sequence[start]) throw new Error(`${file}: incomplete`);

  pets[label] = { label, emoji, speed: speedOf[cls], colors, start, sequence, names, ...OVERRIDES[label] };
}

const missing = Object.values(TYPE).filter((t) => t !== "null" && !pets[t]);
if (missing.length) throw new Error(`no pet file for: ${missing.join(", ")}`);

const out = `// Generated by scripts/gen-pets.mjs from vscode-pets ${tag}. Do not edit by hand.
// Behaviour tables and names: Copyright (c) Anthony Shaw, MIT License (see NOTICE).
export const UPSTREAM_TAG = ${JSON.stringify(tag)};

export const PETS = ${JSON.stringify(pets, null, 2)};

export const TYPES = Object.keys(PETS);
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), "../mods/pets/pets.js");
writeFileSync(dest, out);
console.log(`wrote ${Object.keys(pets).length} pets to ${dest}`);
